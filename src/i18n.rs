#[derive(PartialEq, Clone, Copy, Debug, serde::Serialize, serde::Deserialize)]
pub enum Language {
    Ru,
    Uk,
    En,
}

impl Language {
    #[allow(dead_code)]
    pub fn name(&self) -> &'static str {
        match self {
            Language::Ru => "Русский",
            Language::Uk => "Українська",
            Language::En => "English",
        }
    }
}

#[derive(PartialEq, Clone, Copy, Debug, serde::Serialize, serde::Deserialize)]
pub enum UiScale {
    Normal, // 100%
    Medium, // 115%
    Large,  // 130%
    Huge,   // 145%
}

impl UiScale {
    pub fn factor(&self) -> f32 {
        match self {
            UiScale::Normal => 1.0,
            UiScale::Medium => 1.15,
            UiScale::Large => 1.30,
            UiScale::Huge => 1.45,
        }
    }
}

